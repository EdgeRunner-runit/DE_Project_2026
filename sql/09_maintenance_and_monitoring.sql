SET search_path TO bms;

-- ---------------------------------------------------------------------
-- 1. Buffer Cache Hit Ratio Monitor
-- Evaluates whether table heap blocks are satisfied from RAM (shared_buffers)
-- Target in production: > 99.0%
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW bms.v_cache_hit_ratio AS
SELECT 
    relname AS table_name,
    heap_blks_read,
    heap_blks_hit,
    round(
        (heap_blks_hit::numeric / nullif(heap_blks_hit + heap_blks_read, 0)) * 100, 2
    ) AS cache_hit_pct
FROM pg_statio_user_tables
WHERE schemaname = 'bms'
ORDER BY heap_blks_read DESC;


-- ---------------------------------------------------------------------
-- 2. Index Utilization & Unused Index Detector
-- Tracks index scans (idx_scan) vs sequential scans (seq_scan).
-- Identifies unused indexes consuming disk space and slowing down writes.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW bms.v_index_usage AS
SELECT 
    schemaname,
    relname AS table_name,
    indexrelname AS index_name,
    idx_scan AS index_scans_count,
    pg_size_pretty(pg_relation_size(indexrelid)) AS index_size,
    CASE 
        WHEN idx_scan = 0 THEN 'NEVER USED (Review for Removal)'
        WHEN idx_scan < 50 THEN 'LOW USAGE'
        ELSE 'ACTIVELY USED'
    END AS usage_status
FROM pg_stat_user_indexes
WHERE schemaname = 'bms'
ORDER BY idx_scan ASC, pg_relation_size(indexrelid) DESC;


-- ---------------------------------------------------------------------
-- 3. Table Bloat & Dead Tuple Vacuum Urgency
-- Monitors dead tuples (n_dead_tup) generated by UPDATEs and DELETEs (W03, W04)
-- Flags tables needing manual VACUUM ANALYZE.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW bms.v_table_bloat AS
SELECT 
    relname AS table_name,
    n_live_tup AS live_tuples,
    n_dead_tup AS dead_tuples,
    round(
        (n_dead_tup::numeric / nullif(n_live_tup + n_dead_tup, 0)) * 100, 2
    ) AS dead_tuple_pct,
    last_vacuum,
    last_autovacuum,
    last_analyze
FROM pg_stat_user_tables
WHERE schemaname = 'bms'
ORDER BY n_dead_tup DESC;


-- ---------------------------------------------------------------------
-- 4. Live Lock Contention & Transaction Conflict Monitor
-- Detects concurrent blocking transactions waiting on seat or booking locks.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW bms.v_lock_contention AS
SELECT 
    blocked_locks.pid     AS blocked_pid,
    blocked_activity.usename  AS blocked_user,
    blocking_locks.pid    AS blocking_pid,
    blocking_activity.usename AS blocking_user,
    blocked_activity.query    AS blocked_statement,
    blocking_activity.query   AS blocking_statement,
    now() - blocked_activity.query_start AS waiting_duration
FROM  pg_catalog.pg_locks         blocked_locks
JOIN pg_catalog.pg_stat_activity blocked_activity ON blocked_activity.pid = blocked_locks.pid
JOIN pg_catalog.pg_locks         blocking_locks 
    ON blocking_locks.locktype = blocked_locks.locktype
    AND blocking_locks.database IS NOT DISTINCT FROM blocked_locks.database
    AND blocking_locks.relation IS NOT DISTINCT FROM blocked_locks.relation
    AND blocking_locks.page IS NOT DISTINCT FROM blocked_locks.page
    AND blocking_locks.tuple IS NOT DISTINCT FROM blocked_locks.tuple
    AND blocking_locks.virtualxid IS NOT DISTINCT FROM blocked_locks.virtualxid
    AND blocking_locks.transactionid IS NOT DISTINCT FROM blocked_locks.transactionid
    AND blocking_locks.classid IS NOT DISTINCT FROM blocked_locks.classid
    AND blocking_locks.objid IS NOT DISTINCT FROM blocked_locks.objid
    AND blocking_locks.objsubid IS NOT DISTINCT FROM blocked_locks.objsubid
    AND blocking_locks.pid != blocked_locks.pid
JOIN pg_catalog.pg_stat_activity blocking_activity ON blocking_activity.pid = blocking_locks.pid
WHERE NOT blocked_locks.granted;


-- ---------------------------------------------------------------------
-- 5. Automated Routine: Vacuum and Statistics Recomputation
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE bms.proc_maintenance_vacuum_all()
LANGUAGE plpgsql AS $$
BEGIN
    RAISE NOTICE 'Starting automated VACUUM ANALYZE across schema bms...';
    VACUUM (ANALYZE, VERBOSE) bms.booking_seats;
    VACUUM (ANALYZE, VERBOSE) bms.bookings;
    VACUUM (ANALYZE, VERBOSE) bms.shows;
    VACUUM (ANALYZE, VERBOSE) bms.seats;
    RAISE NOTICE 'Maintenance routine completed successfully.';
END;
$$;
